    /// The glyph as an image source: a full SVG document, built once.
    pub fn src(self) -> ImageSrc {
        thread_local! {
            static CACHE: RefCell<HashMap<Icon, ImageSrc>> = RefCell::new(HashMap::new());
        }
        CACHE.with_borrow_mut(|cache| {
            cache
                .entry(self)
                .or_insert_with(|| {
                    ImageSrc::svg_markup(&format!(
                        r#"<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">{}</svg>"#,
                        self.shapes()
                    ))
                })
                .clone()
        })
    }
