/// An icon at `size` points, in the colour of the text around it unless
/// the caller sets `.text_color(..)`. Decorative: hidden from screen
/// readers (the control that holds it carries the label).
pub fn icon(name: Icon, size: f32) -> Svg {
    svg(name.src())
        .size(px(size))
        .flex_shrink_0()
        .accessibility_elements_hidden(true)
}
